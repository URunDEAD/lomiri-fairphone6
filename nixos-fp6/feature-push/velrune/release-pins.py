#!/usr/bin/env python3
"""Writes velrune/release-pins.nix: components the image takes from the signed CI channel.

usage: release-pins.py CHANNEL_JSON CHANNEL_MINISIG ID... > release-pins.nix
       e.g. release-pins.py velrune.json velrune.json.minisig org.velrune.Shell org.velrune.Settings \
              org.velrune.Clock org.velrune.Capture

The channel (http://100.71.132.112:8088/channel/velrune.json, NetBird only) names, per
component, the commit CI built and the store path it signed into the binary cache. This
records how to evaluate exactly that path again: the component's own recipe and argument
(its release.toml at that commit), its source and every git dependency of its Cargo.lock,
each pinned by commit and NAR hash, called the way velrune-release's entry.nix calls it
(native aarch64-linux, Nixpkgs from velrune-release's pin). velrune-apps.nix evaluates
each pin and stops unless it gives the channel's store path, so the image refers to the
signed release itself and a build only substitutes it from the cache.

The channel signature is checked first (minisign, velrune-channel-2); a channel that does
not verify writes nothing. Commits are read from the local mirrors (git-mirrors.nix);
nothing is fetched from the network.
"""
import json, os, subprocess, sys, tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
# velrune-release keys/velrune-channel-2.pub
CHANNEL_KEY = "RWSl7exEGArJa69UDxblIvqbmj9Y4YHgF0KsS4FUaT6uz0QQAy0lSwZb"
# velrune-release velrune_release/nixpkgs.json: the Nixpkgs every CI release builds with.
NIXPKGS = {"owner": "NixOS", "repo": "nixpkgs",
           "rev": "31ecbaca1bdefa45dffc409f0250bd8039ea0010",
           "narHash": "sha256-dhoW6VgFWlaodSY5jrBn+CF2FLmaUvDVgM7+C7T2+NM="}
# channel id -> (key in release-pins.nix, where it goes)
# Clock and Capture are System-trust apps (rev5n): the Shell honours Clock's over-lock
# alarm window and gives Capture the screen-capture protocols only for system entries.
KEYS = {"org.velrune.Shell": ("shell", "shell"), "org.velrune.Settings": ("settings", "apps"),
        "org.velrune.Clock": ("clock", "apps"), "org.velrune.Capture": ("capture", "apps")}


def run(*cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout


def nix_eval(path):
    return json.loads(run("nix-instantiate", "--eval", "--strict", "--json", path))


def tree_nar_hash(mirror, rev):
    expr = f'(builtins.fetchGit {{ url = "file://{mirror}"; rev = "{rev}"; allRefs = true; }}).narHash'
    return json.loads(run("nix-instantiate", "--eval", "--json", "-E", expr))


def git_deps(lock_text):
    found = set()
    for package in tomllib.loads(lock_text).get("package", []):
        source = package.get("source", "")
        if source.startswith("git+"):
            url, rev = source[4:].split("?", 1)[0], source.rsplit("#", 1)[1]
            if len(rev) != 40:
                sys.exit(f"unpinned git source {source}")
            found.add((url, rev))
    return sorted(found)


def nix_str(s):
    return json.dumps(s)


def main():
    channel_path, signature, ids = sys.argv[1], sys.argv[2], sys.argv[3:]
    run("minisign", "-Vm", channel_path, "-x", signature, "-P", CHANNEL_KEY)
    channel = json.load(open(channel_path))
    mirrors = nix_eval(os.path.join(HERE, "git-mirrors.nix"))
    hosts = nix_eval(os.path.join(HERE, "source-hosts.nix"))
    w = sys.stdout.write
    w("# Generated by release-pins.py from the signed CI channel. Do not edit by hand: rerun it\n"
      "# with a newer channel. Each entry evaluates (velrune-apps.nix) to the store path the\n"
      "# channel names; the build substitutes it from the release cache\n"
      "# (http://100.71.132.112:8088, key velrune-release-2) instead of compiling it.\n{\n")
    w(f"  channel = {{ serial = {channel['serial']}; generated = {nix_str(channel['generated'])}; }};\n")
    w(f"  nixpkgs = {{ owner = {nix_str(NIXPKGS['owner'])}; repo = {nix_str(NIXPKGS['repo'])};\n"
      f"    rev = {nix_str(NIXPKGS['rev'])}; narHash = {nix_str(NIXPKGS['narHash'])}; }};\n")
    entries = {"apps": [], "shell": []}
    for cid in ids:
        key, place = KEYS[cid]
        c = channel["components"][cid]
        url = f"https://github.com/URunDEAD-Labs/{c['repo']}.git"
        mirror = mirrors[url]
        manifest = tomllib.loads(run("git", "-C", mirror, "show", f"{c['rev']}:release.toml"))
        if manifest["component"]["id"] != cid:
            sys.exit(f"{url}@{c['rev']}: release.toml id is {manifest['component']['id']}, not {cid}")
        build = manifest["build"]
        if build.get("extra_sources") or build.get("extras"):
            sys.exit(f"{cid}: extra sources are not supported here")
        deps = git_deps(run("git", "-C", mirror, "show", f"{c['rev']}:Cargo.lock"))
        git = [(u, r, tree_nar_hash(mirrors[hosts[u]], r)) for u, r in deps]
        text = (f"    {key} = {{\n" if place == "apps" else "  shell = {\n")
        text += (f"      id = {nix_str(cid)}; version = {nix_str(c['version'])};\n"
                 f"      out = {nix_str(c['out'])};\n"
                 f"      recipe = {nix_str(build['recipe'])}; arg = {nix_str(build['arg'])};\n"
                 f"      src = {{ url = {nix_str(url)}; rev = {nix_str(c['rev'])};\n"
                 f"        narHash = {nix_str(tree_nar_hash(mirror, c['rev']))}; }};\n"
                 "      gitSources = [\n")
        for u, r, h in git:
            text += f"        {{ url = {nix_str(u)}; rev = {nix_str(r)}; narHash = {nix_str(h)}; }}\n"
        text += "      ];\n" + ("    };\n" if place == "apps" else "  };\n")
        entries[place].append(text)
    w("  apps = {\n" + "".join(entries["apps"]) + "  };\n")
    w("".join(entries["shell"]))
    w("}\n")


if __name__ == "__main__":
    main()
